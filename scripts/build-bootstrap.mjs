// Builds supabase/bootstrap.sql — a single idempotent script containing every
// migration (0001-00NN) rewritten so it is safe to run on an empty project AND
// re-run on a populated one (types/tables/indexes/policies/triggers/inserts
// guarded). Regenerate after adding a migration: node scripts/build-bootstrap.mjs
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const DIR = "supabase/migrations";
const OUT = "supabase/bootstrap.sql";

/** Split SQL into top-level statements, respecting '...', $$...$$, and comments. */
function splitStatements(sql) {
  const stmts = [];
  let cur = "";
  let i = 0;
  const n = sql.length;
  let mode = "code"; // code | single | line | block | dollar
  let tag = "";
  while (i < n) {
    const c = sql[i];
    const two = sql.slice(i, i + 2);
    if (mode === "line") { cur += c; if (c === "\n") mode = "code"; i++; continue; }
    if (mode === "block") { cur += c; if (two === "*/") { cur += sql[++i]; mode = "code"; } i++; continue; }
    if (mode === "single") {
      cur += c;
      if (c === "'") { if (sql[i + 1] === "'") cur += sql[++i]; else mode = "code"; }
      i++; continue;
    }
    if (mode === "dollar") {
      if (sql.startsWith(tag, i)) { cur += tag; i += tag.length; mode = "code"; }
      else { cur += c; i++; }
      continue;
    }
    if (two === "--") { mode = "line"; cur += two; i += 2; continue; }
    if (two === "/*") { mode = "block"; cur += two; i += 2; continue; }
    if (c === "'") { mode = "single"; cur += c; i++; continue; }
    if (c === "$") {
      const m = sql.slice(i).match(/^\$[a-zA-Z_]*\$/);
      if (m) { tag = m[0]; mode = "dollar"; cur += tag; i += tag.length; continue; }
    }
    if (c === ";") { stmts.push(cur); cur = ""; i++; continue; }
    cur += c; i++;
  }
  if (cur.trim()) stmts.push(cur);
  return stmts;
}

const stripComments = (s) =>
  s.replace(/--[^\n]*/g, " ").replace(/\/\*[\s\S]*?\*\//g, " ").trim();

function transform(stmt, file) {
  const code = stripComments(stmt);
  if (!code) return stmt; // pure comment block

  // PostgreSQL enum additions must commit before functions/policies use them.
  // Keep this explicit even when the script is submitted as one SQL batch.
  if (/^alter\s+type\s+[\w.]+\s+add\s+value/i.test(code)) {
    return `${stmt};\ncommit;\nbegin`;
  }

  // create type x as enum -> guard with to_regtype
  let m = code.match(/^create\s+type\s+([\w.]+)\s+as\s+enum/i);
  if (m) {
    const [schema = "public", name] = m[1].includes(".")
      ? m[1].split(".")
      : ["public", m[1]];
    return `do $$\nbegin\n  if to_regtype('${schema}.${name}') is null then\n    ${code};\n  end if;\nend $$`;
  }

  // create table -> if not exists
  if (/^create\s+table\s+/i.test(code) && !/^create\s+table\s+if\s+not\s+exists/i.test(code)) {
    return stmt.replace(/create\s+table\s+/i, (x) => `${x}if not exists `);
  }

  // create [unique] index -> if not exists + generated name when anonymous
  m = code.match(/^(create\s+unique\s+index|create\s+index)\s+(?:if\s+not\s+exists\s+)?(?:(\w+)\s+)?on\s+([\w.]+)\s*\(([^)]+)\)/i);
  if (m) {
    const name = m[2] ?? `${m[3].replace(/^.*\./, "")}_${m[4].split(",")[0].trim().replace(/[^\w]/g, "")}_idx`;
    if (/if\s+not\s+exists/i.test(code)) return stmt;
    return stmt.replace(
      /create\s+(unique\s+)?index\s+(?:[a-zA-Z_]\w*\s+)?on\s+/i,
      (_match, unique = "") => `create ${unique}index if not exists ${name} on `
    );
  }

  // create policy -> drop first
  m = code.match(/^create\s+policy\s+"?([\w\s]+)"?\s+on\s+([\w.]+)/i);
  if (m) {
    return `drop policy if exists "${m[1]}" on ${m[2]};\n${stmt}`;
  }

  // create trigger -> drop first
  m = code.match(/^create\s+trigger\s+(\w+)[\s\S]*?\bon\s+([\w.]+)\s+for\b/i);
  if (m) {
    return `drop trigger if exists ${m[1]} on ${m[2]};\n${stmt}`;
  }

  // insert -> on conflict do nothing
  if (/^insert\s+into\s+/i.test(code) && !/on\s+conflict/i.test(code)) {
    return `${stmt} on conflict do nothing`;
  }

  // alter table add column -> if not exists
  if (/^alter\s+table\s+[\w.]+\s+add\s+column\s+/i.test(code) && !/add\s+column\s+if\s+not\s+exists/i.test(code)) {
    return stmt.replace(/add\s+column\s+/i, "add column if not exists ");
  }

  return stmt;
}

const files = readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort();
let body = "";
const stats = {};
for (const f of files) {
  const sql = readFileSync(join(DIR, f), "utf8");
  const stmts = splitStatements(sql);
  stats[f] = stmts.length;
  body += `\n-- ═══ ${f} ═══\n`;
  for (const s of stmts) {
    const t = transform(s, f).trim();
    if (t) body += `${t};\n`;
  }
}

const header = `-- ============================================================================
-- QUICKRECON FULL BOOTSTRAP — generated by scripts/build-bootstrap.mjs
-- Applies migrations ${files[0]} through ${files[files.length - 1]} in one paste.
-- Review before applying to a populated project: migrations include data changes.
-- Enum additions create transaction boundaries; the full script is not atomic.
-- ============================================================================

begin;
`;
const tail = `
notify pgrst, 'reload schema';
commit;
`;
writeFileSync(OUT, header + body + tail);
console.log("wrote", OUT);
console.table(stats);
